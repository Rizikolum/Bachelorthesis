    [String]$b = "100011000111101110101100110010010100111110001001100011110000100001010111010100000110111010110011101100001101110000100111001010110010001000001111010011001101101011100101111010000111101010100011011101000011101100110111110000010010011110101100000100110011010001101011011011010010010011100011"
    )

#compares two strings of identical length and returns indexes at which they differ, also includes a flag if any errors exist

$comp = [string] ""
$err = $false
$indexes = @()

# if a and b match, write a 0, if not write a 1 to the comparisonstring and remember the index
for ($i = 0; $i -lt $a.length; $i++) {
    if ($a[$i] -eq $b[$i]) { $comp += 0 } else {
        $comp += 1
        $err = $true
        $indexes += $i
    }
}
return [PSCustomObject]@{comp = $comp; err= $err; indexes = $indexes}